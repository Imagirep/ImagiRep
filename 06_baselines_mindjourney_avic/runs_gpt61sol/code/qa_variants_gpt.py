"""[GPT-6.1-sol copy, 2026-10-10: model = gpt_backend.GPTChatAPI; --src_abs = absolute results dir; output under
$GPT_TEST_ROOT/qa/<tag>; everything else identical to imagination_baselines_mj_avic_20261006/code/qa_variants.py]
Stage 1 (2026-10-07): re-run ONLY the final answer call of MindJourney / AVIC on saved imagined frames.

  python qa_variants.py <mj|avic> <dev_ids.json> <variant> [--workers 8]

Variants (each = one final QA call per question, Gemini 3.7 Flash, temp 0, HIGH, enum on choice texts):
  base      the method's own no-imagination answer prompt (format_spatial_vqa_prompt_answer_baseline)
  orig      the saved final prompt as-is (re-run, measures run-to-run noise vs the stored result)
  top1/2/3  MJ: keep only the k imagined views with the highest helpfulness score over all steps
  last      AVIC: keep only the last imagined keyframe (closest to the plan's end pose)
  label     saved final prompt + an explicit note that imagined views are generated and may be wrong
  obsfirst  saved final prompt + "your answer from the real image(s) alone was X; change only on clear evidence"
            (X = this method's `base` prediction; run `base` first)
Results: results/qa_variants/<method>/<variant>/<qid>.json
"""
import glob, json, os, re, sys, threading
from concurrent.futures import ThreadPoolExecutor

R = '<external>/imagination_baselines_mj_avic_20261006'
METHOD, DEV, VAR = sys.argv[1], sys.argv[2], sys.argv[3]
WORKERS = int(sys.argv[sys.argv.index('--workers') + 1]) if '--workers' in sys.argv else 8
CODE = {'mj': R + '/code/MindJourney', 'avic': R + '/code/AVIC/visual_spatial_reasoning'}[METHOD]
sys.path.insert(0, CODE)
from utils.prompt_formatting import format_gpt_content, format_spatial_vqa_prompt_answer_baseline  # noqa: E402
sys.path.insert(0, os.environ['GPT_TEST_ROOT'] + '/code')
from gpt_backend import GPTChatAPI  # noqa: E402

# --src <results dir glob prefix> (default: the FO full run); --tag names the output group
SRC = sys.argv[sys.argv.index('--src') + 1] if '--src' in sys.argv else {'mj': 'mj_bench_r2f6e6/fo622_*', 'avic': 'avic_bench/fo622_*'}[METHOD]
TAG = sys.argv[sys.argv.index('--tag') + 1] if '--tag' in sys.argv else ''
GLOB = sys.argv[sys.argv.index('--src_abs') + 1] + ('/*/{q}/gpt.json' if METHOD == 'mj' else '/*/{q}/step_0/gpt.json')
OUT = f"{os.environ['GPT_TEST_ROOT']}/qa/{TAG}/{METHOD}/{VAR}"
os.makedirs(OUT, exist_ok=True)
NOTE = ("IMPORTANT: The imagined views are generated by a world model from Image 1 and the listed actions. They can be "
        "inaccurate or hallucinated (wrong objects, distorted geometry, wrong distances). Treat them as uncertain hints. "
        "Rely on the real observed image(s) whenever the imagined views conflict with them or look implausible.")
STD = ("Solve the multiple-choice spatial reasoning question using the provided images. Images are labeled; Image 1 is "
       "your current view. Reason carefully about the 3D scene, then output the exact answer from the choices.")
_tl = threading.local()


def api():
    if not hasattr(_tl, 'a'):
        _tl.a = GPTChatAPI('gpt-6.1-sol')
    return _tl.a


def end_keyframe(path, label):
    """AVIC: frame at the END of the k-th macro action (upstream samples the segment CENTRE) from the plan's pred.mp4.
    k = number of actions in the label; atoms per macro = value/0.25 m or value/15 deg (the run's atomic sizes);
    frame index = cumulative atoms / total atoms over the rendered video (same proportional timeline as upstream)."""
    import cv2
    d = os.path.dirname(path); name = os.path.basename(d)[len('plan_'):]
    toks = name.split('_'); macros = [(toks[i], float(toks[i + 1])) for i in range(0, len(toks) - 1, 2)]
    atoms = [max(1, round(v / (0.25 if t == 'move-forward' else 15))) for t, v in macros]
    k = min(len(macros), str(label).count('then ') + 1)
    out = f'{d}/endkf_{k}.png'
    if not os.path.exists(out):
        cap = cv2.VideoCapture(f'{d}/pred.mp4'); n = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
        idx = round(sum(atoms[:k]) / sum(atoms) * (n - 1))
        cap.set(cv2.CAP_PROP_POS_FRAMES, idx); ok, fr = cap.read()
        if not ok:
            return path
        cv2.imwrite(out, fr)
    return out


def split(content):
    """observed head | imagined items | tail, from a saved final-QA content list."""
    i = next(k for k, it in enumerate(content) if len(it) == 1 and str(it[0]).startswith('Below are the imagined views'))
    return content[:i], content[i], content[i + 1:-1], content[-1]


def mj_scores(qdir):
    s = {}
    for f in glob.glob(qdir + '/step_*/gpt_1.json'):
        x = json.load(open(f))
        nums = [int(v) for v in re.findall(r'\d+', (x.get('llm_response') or '').split('Output:')[-1])]
        paths = [it[1] for it in x['prompt']['content'] if len(it) == 2 and 'Imagined image of index' in str(it[0])]
        for p, v in zip(paths, nums):
            s[p] = max(v, s.get(p, -1))
    return s


def keep_images(items, keep):
    """keep only imagined image items whose path is in `keep`; drop action headers left without images."""
    out, header = [], None
    for it in items:
        if len(it) == 2:
            if it[1] in keep:
                if header is not None:
                    out.append(header); header = None
                out.append(it)
        elif str(it[0]).startswith('Action:') and not str(it[0]).strip().endswith(('meters', 'degrees')):
            header = it
        else:
            if out and out[-1] is not None and str(it[0]).strip() == '':
                out.append(it)
    return out


def build(x, qdir, base_pred=None):
    q = x['question']; sysp = x['prompt']['system']; content = [tuple(it) for it in x['prompt']['content']]
    toks = VAR.split('+')
    if 'sys' in toks:
        sysp = STD
    if toks[0] == 'base':
        imgs = [it[1] for it in content if len(it) == 2][:len(q['img_paths'])]
        bs, bc = format_spatial_vqa_prompt_answer_baseline(question=q['question'], answer_choices=q['answer_choices'], images=imgs)
        return (STD if 'sys' in toks else bs, bc), 0
    try:
        head, marker, imag, tail = split(content)
    except StopIteration:            # AVIC skip: no imagined section -> same as saved prompt
        return (sysp, content), 0
    paths = [it[1] for it in imag if len(it) == 2]
    for tok in VAR.split('+'):            # variants compose, e.g. "top3+label"
        if tok.startswith('top'):
            sc = mj_scores(qdir); k = int(tok[3:])
            keep = set(sorted(paths, key=lambda p: (-sc.get(p, -1), paths.index(p)))[:k])
            imag = keep_images(imag, keep)
        elif tok == 'endkf':
            imag = [(it[0], end_keyframe(it[1], it[0])) if len(it) == 2 else it for it in imag]
        elif tok == 'last':
            imag = keep_images(imag, {paths[-1]}) if paths else imag
        elif tok == 'label':
            marker = (str(marker[0]) + '\n' + NOTE + '\n',)
            sysp = sysp + '\n' + NOTE
        elif tok == 'obsfirst':
            tail = (f"Based only on the real observed image(s), your earlier answer was: {base_pred}.\n"
                    "Review the imagined views. Keep that answer unless the imagined views give clear, reliable evidence "
                    "that it is wrong.\n" + str(tail[0]),)
    n = sum(1 for it in imag if len(it) == 2)
    return (sysp, head + [marker] + imag + [tail]), n


def one(qid):
    out = f'{OUT}/{qid}.json'
    if os.path.exists(out):
        return
    g = glob.glob(GLOB.format(q=qid))
    if not g:
        return
    x = json.load(open(g[0])); qdir = os.path.dirname(g[0]) if METHOD == 'mj' else os.path.dirname(os.path.dirname(g[0]))
    base_pred = None
    if 'obsfirst' in VAR.split('+'):
        bp = f"{os.environ['GPT_TEST_ROOT']}/qa/{TAG}/{METHOD}/base/{qid}.json"
        base_pred = json.load(open(bp))['prediction']
    (sysp, content), n = build(x, qdir, base_pred)
    if VAR == 'orig':
        content = [tuple(it) for it in x['prompt']['content']]; sysp = x['prompt']['system']
        n = sum(1 for it in content if len(it) == 2) - len(x['question']['img_paths'])
    choices = list(x['question']['answer_choices'])
    pred = api().get_system_response_with_content(sysp, format_gpt_content(content), enum=choices, role=f'qa_{VAR}').strip()
    rec = dict(qid=qid, method=METHOD, variant=VAR, prediction=pred, gold=x['question']['correct_answer'],
               correct=pred.lower() == x['question']['correct_answer'].lower(), n_imagined=n,
               category=x['question']['question_type'], stored_result=x.get('result'))
    json.dump(rec, open(out + '.tmp', 'w')); os.replace(out + '.tmp', out)


if __name__ == '__main__':
    os.environ.setdefault('GPT_USAGE_LOG', f"{os.environ['GPT_TEST_ROOT']}/usage/qa{TAG}_{METHOD}_{VAR}.jsonl")
    ids = json.load(open(DEV))
    with ThreadPoolExecutor(WORKERS) as ex:
        list(ex.map(one, ids))
    recs = [json.load(open(f)) for f in glob.glob(OUT + '/*.json')]
    n = len(recs); c = sum(r['correct'] for r in recs)
    print(f'{METHOD} {VAR}: {c}/{n} = {100 * c / max(1, n):.1f}  mean imagined {sum(r["n_imagined"] for r in recs) / max(1, n):.2f}')
